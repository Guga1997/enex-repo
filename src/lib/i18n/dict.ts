/** ტექსტს თარგმნის; {0}, {1} … ადგილებში args ჯდება */
export function translate(locale: Locale, text: string, ...args: (string | number)[]): string {
  const out = TABLE[locale]?.[text] ?? text;
  return args.length ? out.replace(/\{(\d+)\}/g, (m, i) => String(args[Number(i)] ?? m)) : out;
}

